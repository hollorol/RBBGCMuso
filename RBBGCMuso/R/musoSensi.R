#' musoSensi
#'
#' Sensitivity analysis for Biome-BGCMuSo based on the output of musoMonte.
#' Supports two methods:
#'   \describe{
#'     \item{"src"}{Standardized Regression Coefficients (default). Fits a linear
#'       model across all Monte Carlo samples and partitions output variance by
#'       parameter. Fast but assumes linearity.}
#'     \item{"boruta"}{Random Forest variable importance via the Boruta algorithm.
#'       Identifies which parameters significantly affect the output without
#'       assuming linearity. Returns Confirmed/Tentative/Rejected decisions.
#'       Requires the \pkg{Boruta} package.}
#'   }
#' @param monteCarloFile Path to a previously saved preservedEpc CSV. If NULL,
#'   musoMonte is run internally.
#' @param settings A list of Monte Carlo environmental variables generated by
#'   setupMuso(). Used only when monteCarloFile is NULL.
#' @param parameters Dataframe with columns: name, EPC row number, min, max.
#' @param inputDir Location of the model input directory.
#' @param outLoc Output directory for Monte Carlo CSV files.
#' @param outVars Output variables to track.
#' @param iterations Number of Monte Carlo runs (used when monteCarloFile is NULL).
#' @param preTag Prefix for Monte Carlo output file names.
#' @param outputType "moreCsv" (default), "oneCsv", or "netCDF".
#' @param fun Aggregation function applied to the time-series model output (default: mean).
#' @param varIndex Which output variable to use as the sensitivity target (1-based).
#' @param outputFile Path for the sensitivity results CSV.
#' @param plotName Path for the sensitivity bar chart PNG.
#' @param plotTitle Title for the sensitivity plot.
#' @param skipSpinup Skip spinup phase after the first run.
#' @param skipZero Replace zero model outputs with NA.
#' @param sourceFile Optional source EPC file.
#' @param postProcString Optional post-processing expression string.
#' @param constraints Parameter constraints passed to musoRand.
#' @param modifyOut Whether to modify the original EPC (TRUE) or a copy.
#' @param dpi Resolution for the saved plot.
#' @param method Sensitivity method: \code{"src"} (Standardized Regression
#'   Coefficients, default) or \code{"boruta"} (Random Forest importance).
#' @param parallel If TRUE, Monte Carlo model runs are parallelised using
#'   doParallel + foreach. Passed through to musoMonte. Default FALSE.
#' @param nCores Number of parallel workers. NULL uses detectCores() - 1.
#' @param sampling Passed through to musoMonte. \code{"auto"} (default)
#'   auto-detects constraints and chooses LHS or MCMC accordingly.
#' @param borutaMaxRuns Maximum number of Boruta iterations (default 100).
#' @param borutaDoTrace Verbosity level for Boruta (0 = silent).
#' @importFrom ggplot2 geom_bar ggplot aes theme element_text xlab ylab ggtitle ggsave scale_y_continuous scale_fill_manual
#' @importFrom scales percent
#' @export

musoSensi <- function(monteCarloFile = NULL,
                     parameters = NULL,
                     settings = NULL,
                     inputDir = "./",
                     outLoc = "./calib",
                     outVars = NULL,
                     iterations = 30,
                     preTag = "mont-",
                     outputType = "moreCsv",
                     fun = mean,
                     varIndex = 1,
                     outputFile = "sensitivity.csv",
                     plotName = "sensitivity.png",
                     plotTitle = "Sensitivity",
                     skipSpinup = TRUE,
                     skipZero = TRUE,
                     sourceFile = NULL,
                     postProcString = NULL,
                     constraints = NULL,
                     modifyOut = TRUE,
                     dpi = 300,
                     method = "src",
                     parallel = FALSE,
                     nCores = NULL,
                     sampling = "auto",
                     borutaMaxRuns = 100,
                     borutaDoTrace = 0){

    method <- match.arg(method, c("src", "boruta"))

    if(is.null(parameters)){
        parameters <- tryCatch(read.csv("parameters.csv",stringsAsFactor=FALSE), error = function (e) {
            stop("You need to specify a path for the parameters.csv, or a matrix.")
        })
    } else {
        if((!is.list(parameters)) & (!is.matrix(parameters))){
             parameters <- tryCatch(read.csv(parameters,stringsAsFactor=FALSE), error = function (e){
                                         stop("Cannot find neither parameters file neither the parameters matrix")
                                     })
        }}
    parameters[,1] <- gsub("([\\s]|\\-epc)","",parameters[,1],perl=TRUE)

    # -------------------------------------------------------------------------
    # Inner analysis function: receives assembled Monte Carlo matrix M where
    # the last column is the model output and the rest are parameter values.
    # -------------------------------------------------------------------------
    doSensi <- function(M){
        npar <- ncol(M) - 1
        M <- M[which(!is.na(M[, ncol(M)])), ]
        M <- M[-1, ]
        y <- M[, (npar + 1)]
        colnames(M) <- gsub("\\.epc", "-epc", colnames(M))
        M <- M[, colnames(M) %in% parameters[, 1], drop = FALSE]
        npar <- ncol(M)
        varNames <- colnames(M)

        if(method == "src"){
            # ------------------------------------------------------------------
            # Standardized Regression Coefficients
            # ------------------------------------------------------------------
            M_c <- apply(M, 2, function(x){ x - mean(x) })
            w <- lm(y ~ M_c)$coefficients[-1]
            Sv <- apply(M_c, 2, var)
            overalVar <- sum(Sv * w^2, na.rm = TRUE)
            S <- numeric(npar)
            for(i in 1:npar){
                S[i] <- ((w[i]^2 * Sv[i]) / overalVar) * 100
            }
            S <- round(S, digits = 2)
            names(S) <- varNames
            write.csv(file = outputFile, x = S)

            sensiPlot <- ggplot(data.frame(name = varNames, y = S / 100),
                                aes(x = name, y = y)) +
                geom_bar(stat = 'identity') +
                theme(axis.text.x = element_text(angle = 45, hjust = 1)) +
                xlab(NULL) +
                ylab(NULL) +
                ggtitle(plotTitle) +
                scale_y_continuous(labels = scales::percent, limits = c(0, 1))
            print(sensiPlot)
            ggsave(plotName, dpi = dpi)
            return(S)

        } else if(method == "boruta"){
            # ------------------------------------------------------------------
            # Boruta: Random Forest variable importance
            # ------------------------------------------------------------------
            if(!requireNamespace("Boruta", quietly = TRUE)){
                stop(paste0("Package 'Boruta' is required for method='boruta'.\n",
                            "Install with: install.packages('Boruta')"))
            }

            M_df <- as.data.frame(M)
            bor <- Boruta::Boruta(M_df, y,
                                  maxRuns = borutaMaxRuns,
                                  doTrace = borutaDoTrace)
            imp <- Boruta::attStats(bor)

            # Align importance table rows with varNames
            imp <- imp[varNames, , drop = FALSE]

            result <- data.frame(
                parameter  = varNames,
                importance = imp$meanImp,
                decision   = imp$decision,
                row.names  = NULL,
                stringsAsFactors = FALSE
            )
            write.csv(file = outputFile, x = result, row.names = FALSE)

            # Normalise importance to [0,1] for the plot
            maxImp <- max(imp$meanImp, na.rm = TRUE)
            plotImp <- if(maxImp > 0) imp$meanImp / maxImp else imp$meanImp

            plotData <- data.frame(
                name       = varNames,
                importance = plotImp,
                decision   = imp$decision,
                stringsAsFactors = FALSE
            )

            sensiPlot <- ggplot(plotData, aes(x = name, y = importance,
                                              fill = decision)) +
                geom_bar(stat = 'identity') +
                scale_fill_manual(
                    values = c("Confirmed" = "steelblue",
                               "Tentative" = "gold",
                               "Rejected"  = "tomato"),
                    name   = "Boruta decision",
                    drop   = FALSE
                ) +
                theme(axis.text.x = element_text(angle = 45, hjust = 1)) +
                xlab(NULL) +
                ylab("Relative importance") +
                ggtitle(plotTitle)
            print(sensiPlot)
            ggsave(plotName, dpi = dpi)

            return(invisible(bor))
        }
    }

    # -------------------------------------------------------------------------
    # Either run musoMonte internally or read an existing result file.
    #
    # When musoMonte is run internally the full parameter x output matrix is
    # saved to <outLoc>/monte_matrix.csv so it can be reused for subsequent
    # SA runs (different varIndex, different method) without re-running the
    # model.  Pass monteCarloFile = file.path(outLoc, "monte_matrix.csv") to
    # reload it.
    # -------------------------------------------------------------------------
    if(is.null(monteCarloFile)){
        M <- musoMonte(parameters  = parameters,
                      settings    = settings,
                      sourceFile  = NULL,
                      inputDir    = inputDir,
                      outLoc      = outLoc,
                      iterations  = iterations,
                      preTag      = preTag,
                      outputType  = outputType,
                      outVars     = outVars,
                      fun         = fun,
                      varIndex    = varIndex,
                      skipSpinup  = skipSpinup,
                      skipZero    = skipZero,
                      postProcString = postProcString,
                      constraints = NULL,
                      modifyOut   = modifyOut,
                      parallel    = parallel,
                      nCores      = nCores,
                      sampling    = sampling
                      )
        M <- cbind(seq_along(M[, 1]), M)

        # Save the full matrix (all outputs) so it can be reused later
        matrixPath <- file.path(outLoc, "monte_matrix.csv")
        tryCatch(
            write.csv(M, file = matrixPath, row.names = FALSE),
            error = function(e)
                warning("Could not save monte_matrix.csv: ", conditionMessage(e))
        )
        message(sprintf(
            "Monte Carlo matrix saved to '%s'. Reuse with monteCarloFile = \"%s\".",
            matrixPath, matrixPath
        ))

        yInd <- grep("mod.", colnames(M))[varIndex]
        M    <- M[, c(grep("mod.", colnames(M), invert = TRUE), yInd)]
        return(doSensi(M))

    } else {
        M    <- read.csv(monteCarloFile)
        yInd <- grep("mod.", colnames(M))[varIndex]
        M    <- M[, c(grep("mod.", colnames(M), invert = TRUE), yInd)]
        return(doSensi(M))
    }
}
